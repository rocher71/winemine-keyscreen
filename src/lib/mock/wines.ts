export const WINES_BY_ID: Record<string, Wine> = WINES.reduce<Record<string, Wine>>((acc, w) => {
  acc[w.id] = w;
  return acc;
}, {});

export function getWine(id: string): Wine | undefined {
  return WINES_BY_ID[id];
}

/** featured 12종만 (스토리·외부평점 보유). */
export function getFeaturedWines(): Wine[] {
  return FEATURED_WINE_IDS.map((id) => WINES_BY_ID[id]).filter(Boolean);
}

/** 사용자가 마신 와인 id 집합 (tasting-notes에서 유도). */
export function getWinesByUser(userId: string, tastedWineIds: string[]): Wine[] {
  void userId;
  return tastedWineIds.map((id) => WINES_BY_ID[id]).filter(Boolean);
}
