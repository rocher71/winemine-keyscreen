/* ─────────────────────────── 기본 expert 필드 빌더 ─────────────────────────── */

function defaultEvolution(openedAtISO: string, decant = false): EvolutionRecord {
  return {
    openedAt: openedAtISO,
    decant,
    timepoints: [
      { minutes: 0, deltaAroma: 0, deltaTannin: 0, deltaBody: 0, score: 70 },
      { minutes: 30, deltaAroma: 1, deltaTannin: -1, deltaBody: 0, score: 78 },
      { minutes: 60, deltaAroma: 2, deltaTannin: -1, deltaBody: 1, score: 86 },
      { minutes: 120, deltaAroma: 1, deltaTannin: -1, deltaBody: 1, score: 88 },
    ],
    peakAt: 60,
  };
}

function mkExp(args: {
  id: string;
  wineId: string;
  source: 'cellar' | 'newEntry';
  cellarItemId?: string | null;
  tastedAt: string;
  rating: number;
  aromas: { categoryId: string; terms: string[] }[];
  caudalies: number;
  servingTemp?: number | null;
  faults?: ExpertFields['faults'];
  intensity?: ExpertFields['intensity'];
  body?: ExpertFields['body'];
  tannin?: ExpertFields['tannin'];
  acidity?: ExpertFields['acidity'];
  finishLength?: ExpertFields['finishLength'];
  peakEstimateYear?: number | null;
  memoKo: string;
  memoEn: string;
  priceKrw?: number | null;
}): TastingNote {
  const evolution = defaultEvolution(args.tastedAt, args.caudalies >= 10);
  return {
    id: args.id,
    userId: 'me-heavy',
    wineId: args.wineId,
    source: args.source,
    cellarItemId: args.cellarItemId ?? null,
    tastedAt: args.tastedAt,
    mode: 'expert',
    beginnerFields: null,
    expertFields: {
      sweetness: 'low',
      acidity: args.acidity ?? 'mediumPlus',
      body: args.body ?? 'mediumPlus',
      tannin: args.tannin ?? 'medium',
      tanninTexture: 'silky',
      intensity: args.intensity ?? 'mediumPlus',
      flavorIntensity: args.intensity ?? 'mediumPlus',
      finishLength: args.finishLength ?? 'long',
      aromaWheel: args.aromas,
      faults: args.faults ?? [],
      evolution,
      caudalies: args.caudalies,
      rating: args.rating,
      memo: { ko: args.memoKo, en: args.memoEn },
      servingTempCelsius: args.servingTemp ?? 17,
      peakEstimateYear: args.peakEstimateYear ?? null,
      peakEstimateConfidence: args.peakEstimateYear ? 'medium' : null,
      peakEstimateNote: null,
    },
    photoUrl: null,
    priceKrw: args.priceKrw ?? null,
    isPublic: true,
    createdAt: args.tastedAt,
  };
}

function mkBeg(args: {
  id: string;
  wineId: string;
  tastedAt: string;
  impression: BeginnerFields['impression'];
  rating: number; // 0~5
  aromas: string[];
  sweetness?: 1 | 2 | 3 | 4 | 5;
  acidity?: 1 | 2 | 3 | 4 | 5;
  body?: 1 | 2 | 3 | 4 | 5;
  tannin?: 1 | 2 | 3 | 4 | 5;
  finish?: BeginnerFields['finish'];
  memoKo: string;
  memoEn: string;
  priceKrw?: number | null;
}): TastingNote {
  return {
    id: args.id,
    userId: 'me-heavy',
    wineId: args.wineId,
    source: 'newEntry',
    cellarItemId: null,
    tastedAt: args.tastedAt,
    mode: 'beginner',
    beginnerFields: {
      impression: args.impression,
      sweetness: args.sweetness ?? 2,
      acidity: args.acidity ?? 4,
      body: args.body ?? 3,
      tannin: args.tannin ?? 3,
      aromas: args.aromas,
      finish: args.finish ?? 'medium',
      rating: args.rating,
      memo: { ko: args.memoKo, en: args.memoEn },
    },
    expertFields: null,
    photoUrl: null,
    priceKrw: args.priceKrw ?? null,
    isPublic: true,
    createdAt: args.tastedAt,
  };
}

